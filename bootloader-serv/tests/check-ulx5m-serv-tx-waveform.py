#!/usr/bin/env python3
"""Decode independently captured USB DATA TX waveform at the GateMate pad stage.

Input is the CSV generated by tb_ulx5m_serv_tx_packet.v (four 48 MHz samples
per full-speed bit). This checker does not use the DUT CRC/NRZI implementation.
"""
import argparse
import csv
from collections import defaultdict
from pathlib import Path

LENGTHS = (0, 8, 16, 18, 27, 64)


def payload_byte(i):
    value = (i * 29 + 7) & 255
    if i % 11 == 0:
        value = 0xff
    if i % 13 == 1:
        value = 0
    return value


def crc16_usb(payload):
    crc = 0xffff
    for byte in payload:
        for bit in range(8):
            feedback = (crc ^ (byte >> bit)) & 1
            crc >>= 1
            if feedback:
                crc ^= 0xa001
    return crc ^ 0xffff


def expect_bytes(packet):
    length = LENGTHS[packet]
    payload = bytes(payload_byte(i) for i in range(length))
    crc = crc16_usb(payload)
    pid = 0xc3 if packet % 2 == 0 else 0x4b
    return bytes((0x80, pid)) + payload + bytes((crc & 255, crc >> 8))


def bits_from_bytes(data):
    return [(byte >> shift) & 1 for byte in data for shift in range(8)]


def nrzi_destuff(bits):
    out = []
    ones = 0
    for bit in bits:
        if ones == 6:
            if bit != 0:
                raise ValueError("invalid stuffed bit after six ones")
            ones = 0
            continue
        out.append(bit)
        ones = ones + 1 if bit else 0
    return out


def candidate(sym, offset, expected):
    # Start in idle J. The first SYNC 0 must transition to K.
    if offset >= len(sym) or sym[offset] != 'K':
        raise ValueError("not a SYNC start")
    prev = 'J'
    wire_bits = []
    eop_index = None
    for pos in range(offset, len(sym)):
        s = sym[pos]
        if s == '0':
            eop_index = pos
            break
        if s not in ('J', 'K'):
            raise ValueError("invalid SE1 symbol")
        wire_bits.append(int(s == prev))
        prev = s
    if eop_index is None or sym[eop_index:eop_index + 3] != ['0', '0', 'J']:
        raise ValueError("EOP must contain two SE0 bits followed by J")
    # Remove bit stuffing as a separate, independently checked operation.
    data_bits = nrzi_destuff(wire_bits)
    required = bits_from_bytes(expected)
    if data_bits != required:
        mismatches = [i for i, (got, want) in enumerate(zip(data_bits, required)) if got != want]
        raise ValueError("PID/payload/CRC mismatch (got %d decoded bits, expected %d; first bad bit %s)" %
                         (len(data_bits), len(required), str(mismatches[0] if mismatches else 'none')))
    # One or more samples of driven idle J are permitted before releasing OE.
    if any(x != 'J' for x in sym[eop_index + 3:]):
        raise ValueError("non-idle symbol after EOP")
    return len(wire_bits) - len(data_bits)


def verify_one(samples, packet, expected=None):
    # Input: (cycle, en, dp, dn). Keep the contiguous asserted OE region.
    active = [s for s in samples if s[1]]
    if not active:
        raise ValueError("packet never asserted pad output-enable")
    start, end = active[0][0], active[-1][0]
    if len(active) != (end - start + 1):
        raise ValueError("output-enable glitch inside packet")
    if any(en for cycle, en, dp, dn in samples if cycle < start or cycle > end):
        raise ValueError("unexpected second TX window")
    mapping = {(1, 0): 'J', (0, 1): 'K', (0, 0): '0', (1, 1): 'X'}
    if expected is None:
        expected = expect_bytes(packet)
    errors = []
    # Resampling the 48 MHz trace with each of four possible bit phases.
    # A leading driven idle J is allowed, so search first few bit positions.
    for phase in range(4):
        symbols = [mapping[(x[2], x[3])] for x in active[phase::4]]
        for offset in range(min(6, len(symbols))):
            try:
                stuffed = candidate(symbols, offset, expected)
                return len(active), stuffed, phase
            except ValueError as exc:
                errors.append(str(exc))
    raise ValueError("could not decode valid DATA packet, examples: " + "; ".join(errors[:3]))


def read_csv(path, packet_count=len(LENGTHS)):
    groups = defaultdict(list)
    with path.open(newline='', encoding='ascii') as f:
        rows = csv.DictReader(f)
        if rows.fieldnames != ['packet', 'cycle', 'en', 'dp', 'dn']:
            raise ValueError("unexpected CSV header")
        for row in rows:
            packet = int(row['packet'])
            if packet < 0 or packet >= packet_count:
                raise ValueError("unknown packet index")
            groups[packet].append(tuple(int(row[key]) for key in ('cycle', 'en', 'dp', 'dn')))
    return groups


def synthetic_trace(packet, bit_phase=0):
    expected = expect_bytes(packet)
    bits = bits_from_bytes(expected)
    stuffed = []
    ones = 0
    for bit in bits:
        stuffed.append(bit)
        ones = ones + 1 if bit else 0
        if ones == 6:
            stuffed.append(0)
            ones = 0
    level = 'J'
    syms = ['J']
    for bit in stuffed:
        if not bit:
            level = 'K' if level == 'J' else 'J'
        syms.append(level)
    syms += ['0', '0', 'J']
    mapping = {'J': (1, 0), 'K': (0, 1), '0': (0, 0)}
    samples = [(c, 0, 1, 0) for c in range(10)]
    for s in syms:
        dp, dn = mapping[s]
        for _ in range(4):
            samples.append((len(samples), 1, dp, dn))
    samples += [(len(samples) + c, 0, 1, 0) for c in range(10)]
    return samples


def selftest():
    for i in range(len(LENGTHS)):
        samples = synthetic_trace(i)
        _, stuffed, _ = verify_one(samples, i)
        if i in (1, 5) and stuffed == 0:
            raise ValueError("selftest did not exercise bit stuffing")
        # Detect CRC corruption, independently of USB RTL.
        corrupted = list(samples)
        active = [j for j, s in enumerate(corrupted) if s[1]]
        center = (len(active) - 12) // 2
        # Corrupt a complete four-sample symbol so every sampling phase
        # observes the error; changing one clock can be resampled away.
        center -= center % 4
        for index in active[center:center + 4]:
            cycle, en, dp, dn = corrupted[index]
            corrupted[index] = (cycle, en, dn, dp)
        try:
            verify_one(corrupted, i)
        except ValueError:
            pass
        else:
            raise ValueError("selftest failed to reject corrupt waveform")
    print('[PASS] independent USB DATA waveform checker selftest (6 lengths, CRC/NRZI/bitstuff/EOP)')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('csv', nargs='?', type=Path)
    parser.add_argument('--selftest', action='store_true')
    args = parser.parse_args()
    if args.selftest:
        selftest()
        return
    if args.csv is None:
        parser.error('CSV path required unless --selftest')
    groups = read_csv(args.csv)
    if set(groups) != set(range(len(LENGTHS))):
        raise ValueError('missing or unexpected packets: ' + str(sorted(groups)))
    for packet, size in enumerate(LENGTHS):
        clocks, stuffed, phase = verify_one(groups[packet], packet)
        print('[PASS] DATA%s len=%d CRC16/stuffing/EOP/OE (samples=%d, stuffed=%d, phase=%d)' %
              ('0' if packet % 2 == 0 else '1', size, clocks, stuffed, phase))


if __name__ == '__main__':
    main()
