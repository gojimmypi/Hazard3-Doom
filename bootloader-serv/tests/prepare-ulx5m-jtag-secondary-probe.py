#!/usr/bin/env python3
"""Offline-only, create-once GateMate JTAG source with a secondary SPI jump.

The initial FPGA image is the previously JTAG-tested cfg-probe heartbeat,
not the walking LED image stored at 0x201000. A different LED pattern is
necessary to tell an actual jump from successful JTAG SRAM programming.

This program never connects to JTAG, USB or SPI and never writes flash.
Its output is NOT authorized for hardware loading by this offline audit.
"""
import argparse
import hashlib
import importlib.util
import os
from pathlib import Path
import subprocess
import tempfile

HERE = Path(__file__).resolve().parent
TARGET = 0x201000
EXPECTED_SOURCE_BIT_SHA = "c298999e6a19604018f0b8be8ceadb3572b95b00d90475c1017fd3a037e9ff84"
EXPECTED_SOURCE_IMPL_SHA = "f5d6386158e9092fdb5b4ed0dd67940ab6b1950a8810643f89b05f54963e8d8b"
EXPECTED_SOURCE_BIT_SIZE = 31411
EXPECTED_SOURCE_IMPL_SIZE = 85947
EXPECTED_COMMAND_PAIR = bytes.fromhex("c3010cfe00ccc6da0428eb001020002951")
# Match Makefile.ulx5m-cfg-probe: the pinned JTAG source uses --reconfig.
SOURCE_PACK_FLAGS = ("--reconfig",)


def sha(data):
    return hashlib.sha256(data).hexdigest()


def check_inputs(reference, implementation):
    bit = Path(reference).read_bytes()
    impl = Path(implementation).read_bytes()
    if len(bit) != EXPECTED_SOURCE_BIT_SIZE or sha(bit) != EXPECTED_SOURCE_BIT_SHA:
        raise ValueError("reference is not pinned, hardware-tested source bitstream")
    if len(impl) != EXPECTED_SOURCE_IMPL_SIZE or sha(impl) != EXPECTED_SOURCE_IMPL_SHA:
        raise ValueError("implementation is not pinned source nextpnr text")
    return bit


def parse_gatemate_command(data, offset):
    # Share the exact CRC/X25 command parser already exercised by v34/v36.
    name = "ulx5m_v43_gatemate_parser"
    path = HERE / "audit-ulx5m-spi-multiboot-commands.py"
    spec = importlib.util.spec_from_file_location(name, path)
    if spec is None or spec.loader is None:
        raise ValueError("missing existing GateMate command audit")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.parse_command(data, offset)


def check_candidate(reference, candidate):
    # Full stream must be regenerated by gmpack; the short pair alone is NOT
    # a proven standalone CC_CFG_CTRL input.
    if not (len(reference) + 17 <= len(candidate) <= len(reference) + 64):
        raise ValueError("unexpected gmpack bootaddr stream size")
    if candidate[:len(reference)-128] != reference[:len(reference)-128]:
        raise ValueError("configuration body differs before terminal region")
    if candidate[-2:] != b"\0\0" or candidate[-19:-2] != EXPECTED_COMMAND_PAIR:
        raise ValueError("expected CRC-pinned reset/jump trailer absent")
    reset = parse_gatemate_command(candidate, len(candidate)-19)
    jump = parse_gatemate_command(candidate, len(candidate)-12)
    if (reset is None or jump is None or
            reset['command'] != 'CMD_CFGRST' or
            reset['payload_hex'] != '00' or
            jump['command'] != 'CMD_JUMP' or
            jump.get('target_le') != '0x%08x' % TARGET):
        raise ValueError("terminal GateMate commands or CRC invalid")
    return {"source_bytes": len(reference), "candidate_bytes": len(candidate),
            "candidate_sha256": sha(candidate), "target": "0x%06x" % TARGET}


def create(reference, implementation, output, packer="gmpack", runner=None):
    if runner is None:
        runner = subprocess.run
    source = check_inputs(reference, implementation)
    output = Path(output)
    if output.suffix != '.bit' or not output.parent.is_dir():
        raise ValueError("output must end in .bit and its parent directory must exist")
    if output.exists():
        raise FileExistsError("output exists; refusing to overwrite it")
    with tempfile.TemporaryDirectory(prefix="ulx5m-v43-offline-") as tmp:
        default = Path(tmp) / 'default.bit'
        variant = Path(tmp) / 'candidate.bit'
        for flags, path in ((SOURCE_PACK_FLAGS, default),
                            (SOURCE_PACK_FLAGS + ("--bootaddr", str(TARGET)), variant)):
            proc = runner([packer, *flags, str(implementation), str(path)],
                          capture_output=True, text=True, check=False)
            if proc.returncode != 0 or not path.is_file():
                raise RuntimeError("gmpack failed or did not emit output: " + proc.stderr)
        if default.read_bytes() != source:
            raise ValueError("gmpack --reconfig cannot reproduce hardware-tested source")
        candidate = variant.read_bytes()
        report = check_candidate(source, candidate)
        # No partially qualified output: create only after all checks pass.
        fd = os.open(str(output), os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o644)
        try:
            with os.fdopen(fd, 'wb') as stream:
                stream.write(candidate)
        except BaseException:
            output.unlink(missing_ok=True)
            raise
    return report


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--reference', type=Path, required=True)
    ap.add_argument('--implementation', type=Path, required=True)
    ap.add_argument('--out', type=Path, required=True)
    ap.add_argument('--packer', default='gmpack')
    args = ap.parse_args()
    try:
        report = create(args.reference, args.implementation, args.out, args.packer)
    except (ValueError, OSError, RuntimeError) as exc:
        ap.exit(1, '[FAIL] %s\n' % exc)
    print('[PASS] Exact JTAG-tested source bitstream and nextpnr implementation')
    print('[PASS] gmpack --reconfig reproduced JTAG-tested source byte for byte')
    print('[PASS] Full candidate stream with CRC-valid reset/jump to ' + report['target'])
    print('[PASS] Created offline-only candidate: ' + str(args.out))
    print('Source bytes:', report['source_bytes'])
    print('Candidate bytes:', report['candidate_bytes'])
    print('Candidate SHA-256:', report['candidate_sha256'])
    print('[BLOCK] No proof JTAG-loaded CMD_JUMP starts autonomous SPI configuration')
    print('[BLOCK] No persistent stage0, independent BTN2 recovery or hardware authorization')
    print('[PASS] No JTAG, USB or flash activity')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
